package ua.magerko.olxradar.data.text

import kotlin.math.max
import kotlin.math.min

/**
 * «Сенсор состояния» — локальный анализатор текста объявления.
 *
 * Читает заголовок и описание и вычисляет оценку состояния лота 0..100:
 *   0  — однозначно нерабочий / сломанный / на запчасти
 *   50 — состояние не указано (уплотнённый нейтральный случай)
 *   100 — уверенно рабочий, «как новый», идеальное состояние
 *
 * Ползунок строгости в настройках радара решает, какая оценка нужна пользователю.
 */
object ConditionAnalyzer {

    /** Чем больше слов найдено, тем сильнее сигнал. */
    private val brokenWords = listOf(
        "нерабочий", "не рабочий", "не работает", "не працюе", "не працює", "неробочий",
        "разбит", "разбита", "разбито", "розбитий", "розбита", "розбите",
        "сломан", "сломаный", "сломанный", "зламаний", "зламана", "зламане",
        "треснут", "треснутый", "трещина", "тріснутий", "тріщина",
        "на запчасти", "на запчастины", "на запчастини", "под запчасти", "під запчастини",
        "дефект", "деффект", "скол", "вмятина", "вогнище",
        "не включается", "не включается", "не вмикається",
        "утопленник", "утоплен", "після води", "попал в воду", "впав у воду",
        "замок", "залочен", "залочений", "заблокирован", "заблокований", "icloud",
        "после ремонта", "після ремонту", "требует ремонта", "потрібен ремонт",
        "проблема", "нестабильно", "глючит", "глючить", "глюк",
        "битый", "бита", "бит", "б/у на детали", "на детали",
        "не отвечает", "не реагирует", "не відповідає"
    )

    private val workingWords = listOf(
        "рабочий", "рабочая", "рабочее", "робочий", "робоча", "робочe",
        "работает", "працює", "працюе", "всё работает", "все работает", "все працює",
        "исправен", "исправный", "справный", "справний", "виправний",
        "идеальное", "идеальний", "відмінний", "отличное", "відмінний стан",
        "как новый", "як новий", "новий", "новое", "новая",
        "без дефектов", "без дефектів", "без проблем", "без пошкоджень",
        "идеал", "повний комплект", "полный комплект",
        "проверен", "проверенный", "перевірений", "тест пройден"
    )

    /** Усиленные сигналы: само слово «нерабочий» весит больше, чем нейтральное «б/у». */
    private val strongBrokenWords = listOf(
        "нерабочий", "не рабочий", "неробочий", "не працює", "не працюе",
        "разбит", "розбитий", "зламаний", "на запчасти", "на запчастини",
        "под запчасти", "під запчастини", "утопленник", "утоплен",
        "не включается", "не вмикається", "замок", "icloud", "заблокирован", "заблокований"
    )

    private val strongWorkingWords = listOf(
        "рабочий", "робочий", "исправен", "справный", "справний", "виправний",
        "идеальное состояние", "відмінний стан", "как новый", "як новий", "новый", "новий"
    )

    /**
     * @return оценка состояния 0..100 (50 — нет информации)
     */
    fun analyze(title: String, description: String): Int {
        val t = (title + " " + description).lowercase()

        var brokenHits = 0
        var workingHits = 0
        var strongBroken = 0
        var strongWorking = 0

        for (w in brokenWords) if (w in t) brokenHits++
        for (w in workingWords) if (w in t) workingHits++
        for (w in strongBrokenWords) if (w in t) strongBroken++
        for (w in strongWorkingWords) if (w in t) strongWorking++

        // Нет сигналов вообще — нейтральная оценка
        if (brokenHits == 0 && workingHits == 0) return 50

        var score = 50
        score += (workingHits - brokenHits) * 12
        score += strongWorking * 15
        score -= strongBroken * 22

        // Сильный сигнал перевешивает всё остальное
        if (strongBroken > 0) score = min(score, 25)
        if (strongWorking > 0 && strongBroken == 0) score = max(score, 75)

        return score.coerceIn(0, 100)
    }

    /**
     * @param score оценка состояния 0..100
     * @param target "working", "broken" или "any"
     * @param threshold строгость 0..100 (0 = фильтр выключен)
     */
    fun matchesTarget(score: Int, target: String, threshold: Int): Boolean {
        if (target == "any" || threshold <= 0) return true
        return when (target) {
            "working" -> score >= threshold
            "broken" -> score <= (100 - threshold)
            else -> true
        }
    }

    /** Человеческое описание оценки для бейджа в интерфейсе. */
    fun describe(score: Int): String = when {
        score >= 75 -> "отличное"
        score >= 55 -> "рабочее"
        score >= 45 -> "неизвестно"
        score >= 25 -> "сомнительное"
        else -> "сломано"
    }
}
